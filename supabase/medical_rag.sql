create extension if not exists vector;

create table if not exists public.medical_chunks (
  id bigint generated by default as identity primary key,
  dataset_group text not null,
  record_type text not null,
  source_file text not null,
  record_title text,
  summary text not null,
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  embedding vector(1536) not null,
  created_at timestamptz not null default now()
);

create index if not exists medical_chunks_embedding_idx
  on public.medical_chunks
  using ivfflat (embedding vector_cosine_ops)
  with (lists = 100);

create index if not exists medical_chunks_dataset_group_idx on public.medical_chunks (dataset_group);
create index if not exists medical_chunks_record_type_idx on public.medical_chunks (record_type);
create index if not exists medical_chunks_source_file_idx on public.medical_chunks (source_file);
create index if not exists medical_chunks_record_title_idx on public.medical_chunks (record_title);

alter table public.medical_chunks enable row level security;

drop policy if exists "Public read medical chunks" on public.medical_chunks;
create policy "Public read medical chunks"
on public.medical_chunks
for select
using (true);

drop policy if exists "Public insert medical chunks" on public.medical_chunks;
create policy "Public insert medical chunks"
on public.medical_chunks
for insert
with check (true);

create or replace function public.match_medical_chunks(
  query_embedding vector(1536),
  match_count integer default 8,
  dataset_group_filter text default null
)
returns table (
  id bigint,
  dataset_group text,
  record_type text,
  source_file text,
  record_title text,
  summary text,
  content text,
  metadata jsonb,
  similarity float
)
language plpgsql
stable
as $$
begin
  if dataset_group_filter is null then
    return query
    select
      mc.id,
      mc.dataset_group,
      mc.record_type,
      mc.source_file,
      mc.record_title,
      mc.summary,
      mc.content,
      mc.metadata,
      (1 - (mc.embedding <=> query_embedding))::float as similarity
    from public.medical_chunks mc
    order by mc.embedding <=> query_embedding
    limit match_count;
  else
    return query
    select
      mc.id,
      mc.dataset_group,
      mc.record_type,
      mc.source_file,
      mc.record_title,
      mc.summary,
      mc.content,
      mc.metadata,
      (1 - (mc.embedding <=> query_embedding))::float as similarity
    from public.medical_chunks mc
    where mc.dataset_group = dataset_group_filter
    order by mc.embedding <=> query_embedding
    limit match_count;
  end if;
end;
$$;