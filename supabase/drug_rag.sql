create extension if not exists vector;

create table if not exists public.drug_chunks (
  id bigint generated by default as identity primary key,
  source_file text not null,
  drug_name text,
  generic_name text,
  brand text,
  form text,
  route text,
  strength text,
  summary text not null,
  content text not null,
  uses text,
  side_effects text,
  availability text,
  metadata jsonb not null default '{}'::jsonb,
  embedding vector(1536) not null,
  created_at timestamptz not null default now()
);

create index if not exists drug_chunks_embedding_idx
  on public.drug_chunks
  using ivfflat (embedding vector_cosine_ops)
  with (lists = 100);

create index if not exists drug_chunks_generic_name_idx on public.drug_chunks (generic_name);
create index if not exists drug_chunks_drug_name_idx on public.drug_chunks (drug_name);

alter table public.drug_chunks enable row level security;

drop policy if exists "Public read drug chunks" on public.drug_chunks;
create policy "Public read drug chunks"
on public.drug_chunks
for select
using (true);

create or replace function public.match_drug_chunks(
  query_embedding vector(1536),
  match_count integer default 8
)
returns table (
  id bigint,
  source_file text,
  drug_name text,
  generic_name text,
  brand text,
  form text,
  route text,
  strength text,
  summary text,
  content text,
  uses text,
  side_effects text,
  availability text,
  metadata jsonb,
  similarity float
)
language sql
stable
as $$
  select
    id,
    source_file,
    drug_name,
    generic_name,
    brand,
    form,
    route,
    strength,
    summary,
    content,
    uses,
    side_effects,
    availability,
    metadata,
    1 - (embedding <=> query_embedding) as similarity
  from public.drug_chunks
  order by embedding <=> query_embedding
  limit match_count;
$$;
